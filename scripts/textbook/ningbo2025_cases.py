import hashlib

PREFIX = "ningbo-2025:"


def C(source, book, lesson, short, title, author, school, note="", videos=None, tools=None, **extra):
    key = hashlib.sha256((PREFIX + source).encode("utf-8")).hexdigest()[:32]
    item = {"source": source, "bookCode": book, "sectionKey": lesson, "shortTitle": short,
            "title": title, "author": author, "school": school, "note": note,
            "sourceKey": key, "videos": videos or {}, "tools": tools or {},
            "status": extra.pop("status", "PUBLISHED")}
    item.update(extra)
    return item


def V(path, include=True, reason="", evidence=""):
    return path, ({"include": include, "reason": reason, "evidence": evidence} if not include
                  else {"include": True, "evidence": evidence})


def T(path, title, description, requirements):
    return path, {"title": title, "description": description, "requirements": requirements}


def videos(*items):
    return {path: decision for path, decision in items}


def tools(*items):
    return {path: payload for path, payload in items}


